/** 候选去重后的全集，用于「推荐」组与分组去重 */
const ALL_ICONS = ICON_GROUPS.flatMap((group) => group.icons);

/**
 * 按分类名推荐图标。命中多个关键词时按出现顺序合并去重。
 * 没有命中时回退到父级图标（若提供）+ 常用兜底，保证推荐区不为空。
 */
export function suggestIcons(name: string, parentIcon?: string): string[] {
  const trimmed = name.trim();
  const matched: string[] = [];

  if (trimmed) {
    for (const [keyword, icons] of KEYWORD_ICONS) {
      if (trimmed.includes(keyword)) {
        for (const icon of icons) {
          if (!matched.includes(icon)) matched.push(icon);
        }
      }
    }
  }

  if (parentIcon && !matched.includes(parentIcon)) {
    matched.unshift(parentIcon);
  }

  if (matched.length === 0) {
    return ALL_ICONS.slice(0, 5);
  }
  return matched.slice(0, 10);
}
